public class Q2 {
    static int multiply(int a, int b) {
        return a * b;
    }

    static double multiply(double a, double b) {
        return a * b;
    }

    public static void main(String[] args) {
        System.out.println(multiply(30, 40));
        System.out.println(multiply(10.3, 3.3));
    }
}
